/** Exercise actual MonitorScreen handlers without WebGL or a browser runtime. */
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const Module = require('module');
const ts = require('typescript');
const filename = path.resolve(__dirname,'../../src/Application/World/MonitorScreen.ts');
const mod = new Module(filename,module);
mod.filename=filename;mod.paths=module.paths;
const keys={IDLE:'idle',DESK:'desk',LOADING:'loading',MONITOR:'monitor',DRAWER:'drawer'};
mod.require = name => {
    if(name === '../Application')return {default:class {}};
    if(name === '../Camera/Camera')return {default:class {},CameraKey:keys};
    if(name === '../Utils/EventEmitter')return {default:class {}};
    if(name.includes('CSS3DRenderer'))return {CSS3DObject:class {}};
    return require(name);
};
mod._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2018}}).outputText,filename);
const screen=Object.create(mod.exports.default.prototype);
const listeners=new Map();
global.document={addEventListener:(name,fn)=>listeners.set(name,fn)};
const calls=[];
const closures=[];
const drawer={open:false,setOpen(open,event,focusCamera){closures.push({open,focusCamera});this.open=open;}};
screen.application={mouse:{trigger:()=>{}},world:{deskAndChair:{drawer}}};
screen.camera={currentKeyframe:keys.IDLE,targetKeyframe:undefined,freeCam:false,trigger:name=>calls.push(name)};
screen.prevInComputer=false;screen.inComputer=false;screen.monitorActive=false;screen.mouseClickInProgress=false;screen.shouldLeaveMonitor=false;
screen.initializeScreenEvents();
const inside={inComputer:true,target:{id:'computer-screen'}};
const outside={inComputer:false,target:{id:''}};
listeners.get('mousemove')(inside);
listeners.get('mousemove')(inside);
assert.deepStrictEqual(calls,[],'hover must never enter the laptop');
listeners.get('mouseup')(inside);
screen.camera.currentKeyframe=keys.LOADING;
listeners.get('mousedown')(inside);
assert.deepStrictEqual(calls,[],'loading clicks must not enter');
listeners.get('mouseup')(inside);
screen.camera.currentKeyframe=keys.DESK;screen.camera.targetKeyframe=keys.IDLE;
listeners.get('mousedown')(inside);
assert.deepStrictEqual(calls,[],'a transitioning camera must ignore entry');
listeners.get('mouseup')(inside);
screen.camera.targetKeyframe=undefined;
listeners.get('mousedown')(inside);
assert.deepStrictEqual(calls,['enterMonitor'],'an explicit screen click must enter');
listeners.get('mouseup')(inside);
listeners.get('mousemove')(outside);
assert.deepStrictEqual(calls,['enterMonitor'],'moving off the screen must not leave it');
listeners.get('mousedown')(inside);listeners.get('mouseup')(outside);
assert.deepStrictEqual(calls,['enterMonitor'],'a click or drag that starts on the screen must not leave it');
listeners.get('mousedown')(outside);
assert.deepStrictEqual(calls,['enterMonitor','leftMonitor'],'a click outside the screen must leave it');
listeners.get('mouseup')(outside);
listeners.get('mousemove')(inside);
assert.equal(calls.length,2,'hover re-entry must not zoom');
// Full handoff from settled or still-opening drawer view; camera entry
// must not accidentally request an intermediate desk transition.
for (const opening of [false,true]) {
    screen.camera.currentKeyframe=opening?undefined:keys.DRAWER;
    screen.camera.targetKeyframe=opening?keys.DRAWER:undefined;
    drawer.open=true;
    const before=calls.length;
    listeners.get('mousemove')(inside);assert.equal(calls.length,before,'drawer hover must not zoom');
    listeners.get('mousedown')(inside);listeners.get('mouseup')(inside);
    assert.equal(calls.at(-1),'enterMonitor');assert(screen.monitorActive&&!drawer.open);
    assert.deepEqual(closures.at(-1),{open:false,focusCamera:false});
    screen.camera.targetKeyframe=undefined;screen.camera.currentKeyframe=keys.MONITOR;
    listeners.get('mousedown')(inside);listeners.get('mouseup')(inside);
    assert.equal(calls.length,before+1,'desktop interaction must not re-enter');
    screen.leaveMonitor();assert.equal(calls.at(-1),'leftMonitor');
}
screen.camera.currentKeyframe=keys.DRAWER;
screen.camera.freeCam=true;
const before=calls.length;listeners.get('mousedown')(inside);
assert.equal(calls.length,before,'Free Camera must retain input ownership');
screen.camera.freeCam=false;screen.camera.introPlaying=true;
listeners.get('mousedown')(inside);assert.equal(calls.length,before,'intro must retain its click-to-skip lock');
delete global.document;
console.log('PASS: explicit entry from desk/idle/drawer, including opening glide; closes drawer without competing camera move; desktop input/back and intro/Free Camera locks preserved; hover never zooms');
